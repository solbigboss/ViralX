export function parseTweetUrl(url: string): TweetMediaData {
  const cleanUrl = url.trim();
  if (cleanUrl.toLowerCase().includes('space')) {
    return SAMPLE_TWEETS.spaces;
  }
  if (cleanUrl.toLowerCase().includes('broadcast') || cleanUrl.toLowerCase().includes('stream')) {
    return SAMPLE_TWEETS.stream;
  }
  if (cleanUrl.toLowerCase().includes('natgeo') || cleanUrl.toLowerCase().includes('wildlife')) {
    return SAMPLE_TWEETS.wildlife;
  }
  if (cleanUrl.toLowerCase().includes('champions') || cleanUrl.toLowerCase().includes('goal') || cleanUrl.toLowerCase().includes('football')) {
    return SAMPLE_TWEETS.football;
  }
  
  // Default to SpaceX or generate a realistic object matching the URL
  const tweetIdMatch = cleanUrl.match(/status\/(\d+)/i);
  const id = tweetIdMatch ? tweetIdMatch[1] : '1839201948192841024';
  const handleMatch = cleanUrl.match(/(?:x|twitter)\.com\/([^/]+)/i);
  const handle = handleMatch && handleMatch[1] !== 'i' ? handleMatch[1] : 'viral_x';

  return {
    ...SAMPLE_TWEETS.spacex,
    id,
    originalUrl: cleanUrl,
    author: {
      name: handle.charAt(0).toUpperCase() + handle.slice(1),
      handle: handle,
      avatar: `https://api.dicebear.com/7.x/shapes/svg?seed=${handle}`,
      verified: true,
    },
    tweetText: `High-definition media extracted from X status: ${cleanUrl}`,
  };
}
